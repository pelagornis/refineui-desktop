//! Machine-readable component contracts (brief §8: "keep component
//! contracts machine-readable").
//!
//! The canonical data is JSON under `crates/refineui-foundation/contracts/`:
//!
//! * `schema.json` — JSON Schema (draft 2020-12) for one contract;
//! * `components/<id>.json` — one contract per component: layer, status,
//!   interaction states, sizes per density, tokens used, keyboard map,
//!   focus behaviour and accessibility role;
//! * `density.json` — every density-dependent metric, generated from
//!   [`crate::size::Density`] by [`density_json`] (a test keeps it in sync).
//!
//! This module embeds those files (no parsing, no dependencies) and defines
//! the shared vocabulary as plain enums, so renderers other than GPUI can use
//! the same contracts.

use crate::size::{ControlMetrics, ControlSize, Density};

/// The eight interaction states every interactive component must define
/// (brief §7).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum InteractionState {
    /// Resting.
    Default,
    /// Pointer over the element.
    Hovered,
    /// Pointer / key down.
    Pressed,
    /// Keyboard focus (`:focus-visible` — the focus ring).
    Focused,
    /// Not operable.
    Disabled,
    /// Busy; not operable until done.
    Loading,
    /// Chosen / checked / current.
    Selected,
    /// Being dragged, or a drop target under a drag.
    Dragging,
}

impl InteractionState {
    /// All states, in contract order.
    pub const ALL: [InteractionState; 8] = [
        Self::Default,
        Self::Hovered,
        Self::Pressed,
        Self::Focused,
        Self::Disabled,
        Self::Loading,
        Self::Selected,
        Self::Dragging,
    ];

    /// Contract key.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Default => "default",
            Self::Hovered => "hovered",
            Self::Pressed => "pressed",
            Self::Focused => "focused",
            Self::Disabled => "disabled",
            Self::Loading => "loading",
            Self::Selected => "selected",
            Self::Dragging => "dragging",
        }
    }
}

/// Architecture layer (brief §3).
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum Layer {
    /// Tokens, theme, density, elevation, motion.
    Foundation,
    /// Focus, keyboard, selection, pointer, drag and drop.
    Interaction,
    /// Buttons, inputs, menus, dialogs, tables, trees.
    Components,
    /// Split views, panels, docks, inspectors, tab groups.
    Composition,
    /// Window, titlebar, toolbar, menu bar, application shell.
    Application,
    /// macOS / Windows / Linux integration.
    Platform,
}

impl Layer {
    /// All layers, bottom first.
    pub const ALL: [Layer; 6] = [
        Self::Foundation,
        Self::Interaction,
        Self::Components,
        Self::Composition,
        Self::Application,
        Self::Platform,
    ];

    /// Contract key.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Foundation => "foundation",
            Self::Interaction => "interaction",
            Self::Components => "components",
            Self::Composition => "composition",
            Self::Application => "application",
            Self::Platform => "platform",
        }
    }
}

/// How a component takes part in Tab order.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum TabStop {
    /// Not focusable.
    None,
    /// One Tab stop.
    Single,
    /// One Tab stop for the group; arrows move inside (roving focus).
    Roving,
    /// Not focusable itself; its children are.
    Container,
    /// Traps focus while open and restores it on close (modal surfaces).
    Trap,
}

impl TabStop {
    /// Contract key.
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::None => "none",
            Self::Single => "single",
            Self::Roving => "roving",
            Self::Container => "container",
            Self::Trap => "trap",
        }
    }
}

/// One embedded contract file.
#[derive(Clone, Copy, Debug)]
pub struct ContractFile {
    /// Kebab-case id (file stem).
    pub id: &'static str,
    /// The JSON document.
    pub json: &'static str,
}

/// JSON Schema for a component contract.
pub const SCHEMA: &str = include_str!("../contracts/schema.json");
/// Density metrics (generated by [`density_json`]).
pub const DENSITY: &str = include_str!("../contracts/density.json");

include!("../contracts/index.rs");

/// The contract with `id`.
pub fn get(id: &str) -> Option<&'static ContractFile> {
    ALL.iter().find(|c| c.id == id)
}

fn metrics_json(m: ControlMetrics) -> String {
    format!(
        "{{\"height\": {}, \"padding_x\": {}, \"padding_y\": {}, \"radius\": {}, \"text_size\": {}, \"icon\": {}}}",
        num(m.height),
        num(m.padding_x),
        num(m.padding_y),
        num(m.radius),
        num(m.text.size),
        num(m.icon)
    )
}

fn num(v: f32) -> String {
    if v.fract() == 0.0 {
        format!("{}", v as i64)
    } else {
        format!("{v}")
    }
}

/// `density.json`: every density-dependent metric from [`Density`].
pub fn density_json() -> String {
    let mut out = String::from("{\n");
    for (di, d) in Density::ALL.iter().enumerate() {
        out.push_str(&format!("  \"{}\": {{\n", d.label()));
        for (name, f) in [
            (
                "button",
                Density::button as fn(Density, ControlSize) -> ControlMetrics,
            ),
            ("field", Density::field),
            ("select", Density::select),
            ("chip", Density::chip),
        ] {
            out.push_str(&format!("    \"{name}\": {{"));
            for (si, s) in ControlSize::ALL.iter().enumerate() {
                out.push_str(&format!(
                    "{}\"{}\": {}",
                    if si == 0 { "" } else { ", " },
                    s.label(),
                    metrics_json(f(*d, *s))
                ));
            }
            out.push_str("},\n");
        }
        let m = d.desktop();
        out.push_str(&format!(
            "    \"desktop\": {{\"row_height\": {}, \"tree_row_height\": {}, \"tab_height\": {}, \"toolbar_height\": {}, \"status_bar_height\": {}, \"panel_header_height\": {}, \"activity_bar_width\": {}, \"activity_item\": {}, \"panel_padding\": {}, \"gap\": {}, \"icon\": {}, \"splitter_hit\": {}}}\n",
            num(m.row_height),
            num(m.tree_row_height),
            num(m.tab_height),
            num(m.toolbar_height),
            num(m.status_bar_height),
            num(m.panel_header_height),
            num(m.activity_bar_width),
            num(m.activity_item),
            num(m.panel_padding),
            num(m.gap),
            num(m.icon),
            num(m.splitter_hit),
        ));
        out.push_str(if di + 1 == Density::ALL.len() {
            "  }\n"
        } else {
            "  },\n"
        });
    }
    out.push_str("}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    /// `density.json` must match the Rust metrics. Regenerate with
    /// `UPDATE_CONTRACTS=1 cargo test -p refineui-foundation`.
    #[test]
    fn density_json_is_current() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/contracts/density.json");
        let want = density_json();
        if std::env::var_os("UPDATE_CONTRACTS").is_some() {
            std::fs::write(path, &want).unwrap();
            return;
        }
        assert_eq!(
            DENSITY, want,
            "contracts/density.json is stale; run UPDATE_CONTRACTS=1 cargo test -p refineui-foundation"
        );
    }

    /// Every file in `contracts/components` is embedded in [`ALL`] (and
    /// vice versa), and each embeds its own id.
    #[test]
    fn index_lists_every_contract_file() {
        let dir = concat!(env!("CARGO_MANIFEST_DIR"), "/contracts/components");
        let mut files: Vec<String> = std::fs::read_dir(dir)
            .unwrap()
            .filter_map(|e| {
                let p = e.ok()?.path();
                if p.extension()? != "json" {
                    return None;
                }
                Some(p.file_stem()?.to_string_lossy().into_owned())
            })
            .collect();
        files.sort();
        let mut ids: Vec<String> = ALL.iter().map(|c| c.id.to_string()).collect();
        ids.sort();
        assert_eq!(files, ids, "contracts/index.rs is out of date");
        for c in ALL {
            assert!(
                c.json.contains(&format!("\"id\": \"{}\"", c.id)),
                "{} does not declare its id",
                c.id
            );
        }
        assert!(SCHEMA.contains("\"$schema\""));
    }
}
