def doc_text(lines):
    """`///` lines → one paragraph: fenced code blocks are dropped (the
    page has its own example) and "See the module docs." pointers too (the
    page *is* the module docs)."""
    out=[]; fence=False
    for l in lines:
        if l.startswith('```'): fence=not fence; continue
        if not fence: out.append(l)
    return re.sub(r'\s*See the module docs\.','',' '.join(out)).strip()

def parse_file(path):
    lines=open(path).read().split('\n')
    types={'*fns':{'kind':'fns','doc':'','variants':[],'methods':[]}}
    i=0
    doc=[]; feat=None
    while i<len(lines):
        l=lines[i]; s=l.strip()
        if s.startswith('///'):
            doc.append(s[3:].strip()); i+=1; continue
        if s.startswith('#['):
            m=re.search(r'feature *= *"([^"]+)"', s)
            if m and not l.startswith(' '): feat=m.group(1)
            i+=1; continue
        if l.startswith('pub fn '):
            # Free function: signature up to the body.
            sig=l.strip()
            while not sig.rstrip().endswith('{') and i+1<len(lines):
                i+=1; sig+=' '+lines[i].strip()
            sig=re.sub(r'\s+',' ',sig).rstrip('{ ').replace('( ','(').replace(', )',')').replace(',)',')')
            d=doc_text(doc)+(f' *(feature `{feat}`)*' if feat else '')
            types['*fns']['methods'].append((sig[4:],d))
            doc=[]; feat=None; i+=1; continue
        m=re.match(r'pub (struct|enum|type) (\w+)',s)
        if m and not l.startswith(' '):
            kind,name=m.groups()
            t=types.setdefault(name,{'kind':kind,'doc':doc_text(doc),'variants':[],'methods':[]})
            t['doc']=doc_text(doc) or t['doc']; t['kind']=kind
            if kind=='enum':
                vdoc=[]; i+=1
                while not lines[i].startswith('}'):
                    v=lines[i].strip()
                    if v.startswith('///'): vdoc.append(v[3:].strip())
                    elif re.match(r'^[A-Z]\w*(\(.*\))?,$',v): t['variants'].append((v.rstrip(','),doc_text(vdoc))); vdoc=[]
                    elif re.match(r'^[A-Z]\w* \{$',v):
                        # Struct variant: list it as `Name { .. }`, skip its fields.
                        t['variants'].append((v[:-2]+' { .. }',doc_text(vdoc))); vdoc=[]
                        while not lines[i].strip().startswith('}'): i+=1
                    i+=1
            doc=[]; i+=1; continue
        m=re.match(r'^impl(?:<[^>]*>)? (\w+) \{',l)
        if m:
            name=m.group(1); t=types.setdefault(name,{'kind':'struct','doc':'','variants':[],'methods':[]})
            i+=1; mdoc=[]
            while i<len(lines) and not lines[i].startswith('}'):
                v=lines[i].strip()
                if v.startswith('///'): mdoc.append(v[3:].strip())
                elif v.startswith('pub fn') or v.startswith('pub const'):
                    sig=v
                    while not (sig.rstrip().endswith('{') or sig.rstrip().endswith(';')) and i+1<len(lines):
                        i+=1; sig+=' '+lines[i].strip()
                    sig=re.sub(r'\s+',' ',sig).rstrip('{; ').replace('( ','(').replace(', )',')')
                    if v.startswith('pub fn'):
                        t['methods'].append((sig[4:],doc_text(mdoc)))
                    mdoc=[]
                elif v and not v.startswith('#['): mdoc=[] if not v.startswith('//') else mdoc
                i+=1
        doc=[]; i+=1
    return types

