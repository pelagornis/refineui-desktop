"""Generate the docs pages that mirror the code (docs/src/content/docs/).

This script is the single source of truth for every page under
components/, foundations/, shell/, workspace/ and reference/:

* one page per gallery story (same id, same order, same sidebar group).
  Its text (summary, usage notes, Rust example, motion, extra sections) is
  written below with `page(...)`, `MOTION` and `EXTRA`; the API tables come
  from the `///` docs and `pub fn` signatures in the crate sources;
* reference/<crate>.mdx: every public item of every crate with the first
  line of its `///` doc.

* architecture/inventory.mdx: every page and every component contract.

Generated pages start with a "Generated by scripts/gen_docs.py" comment.
Edit this file, not those pages. Every other page (index, getting-started/,
the rest of architecture/, guides/, report/) is written by hand and never
touched.

  python3 scripts/gen_docs.py           write pages that changed, delete stale ones
  python3 scripts/gen_docs.py --check   change nothing; exit 1 if any page is out of date

Running it twice changes nothing the second time.
"""
