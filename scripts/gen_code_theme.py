#!/usr/bin/env python3
"""Generate crates/refineui/src/components/code_theme_data.rs from the Shiki
Night Owl (dark) / Night Owl Light themes the web docs use for code
(`docs/src/remark/remarkDocsCode.mjs`: THEMES = night-owl-light / night-owl).

Needs the docs dependencies installed (`cd docs && bun install`) and bun:

  python3 scripts/gen_code_theme.py
"""
import json, pathlib, subprocess, tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
THEMES = ROOT / 'docs/node_modules/@shikijs/themes/dist'
OUT = ROOT / 'crates/refineui/src/components/code_theme_data.rs'

dump = f"""
import a from '{THEMES}/night-owl.mjs';
import b from '{THEMES}/night-owl-light.mjs';
const pick = t => ({{fg: t.colors['editor.foreground'], tokenColors: t.tokenColors}});
console.log(JSON.stringify({{dark: pick(a), light: pick(b)}}));
"""
with tempfile.NamedTemporaryFile('w', suffix='.mjs', delete=False) as f:
    f.write(dump)
data = json.loads(subprocess.check_output(['bun', f.name], cwd=ROOT / 'docs'))

def rgba(hexstr):
    h = hexstr.lstrip('#')
    if len(h) == 3: h = ''.join(c * 2 for c in h)
    if len(h) == 6: h += 'ff'
    return int(h, 16)

def style_bits(fs):
    bits = 0
    for w in (fs or '').split():
        bits |= {'bold': 1, 'italic': 2, 'underline': 4}.get(w, 0)
    return bits

def rules(theme):
    out = []
    for tc in theme['tokenColors']:
        scope = tc.get('scope')
        if not scope: continue
        if isinstance(scope, list): scope = ', '.join(scope)
        s = tc.get('settings', {})
        fg = s.get('foreground'); fs = s.get('fontStyle')
        if fg is None and fs is None: continue
        fgv = f'Some(0x{rgba(fg):08x})' if fg else 'None'
        out.append(f'    ({json.dumps(scope)}, {fgv}, {style_bits(fs) if fs is not None else 255}),')
    return '\n'.join(out)

src = f"""// Generated by scripts/gen_code_theme.py from Shiki's Night Owl themes — do not edit.
//! Night Owl (dark) / Night Owl Light token rules, as used by the web docs code frames.
//! Each rule: (scope selector, foreground `0xRRGGBBAA`, font style bits — 1 bold,
//! 2 italic, 4 underline, 255 = unset).

pub(crate) type Rule = (&'static str, Option<u32>, u8);

/// Night Owl default foreground.
pub(crate) const DARK_FG: u32 = 0x{rgba(data['dark']['fg']):08x};
/// Night Owl Light default foreground.
pub(crate) const LIGHT_FG: u32 = 0x{rgba(data['light']['fg']):08x};

pub(crate) const DARK: &[Rule] = &[
{rules(data['dark'])}
];

pub(crate) const LIGHT: &[Rule] = &[
{rules(data['light'])}
];
"""
OUT.write_text(src)
print('wrote', OUT.relative_to(ROOT))
